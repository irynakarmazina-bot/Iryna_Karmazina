#!/bin/bash
# Черга для перерахунку фінзвіту (run.sh) — «один виконується, максимум один чекає».
#
# Навіщо (аудит 02.08.2026 + рішення користувачки 03.08.2026):
# запустити перерахунок можна кількома способами одночасно — кнопка «⟳ Підтягнути
# свіжі дані» у «Фінансах», кнопка в «Бух. обліку», нічний cron. Раніше кожне
# натискання одразу стартувало ще один run.sh, і два процеси писали в ОДНІ Й ТІ САМІ
# файли (normalized/*, computed/*). Звіт міг прочитати наполовину перезаписані дані.
#
# Правило черги:
#   - ніхто не рахує  → рахуємо одразу;
#   - хтось рахує, черга порожня → СТАЄМО В ЧЕРГУ і рахуємо після нього;
#   - хтось рахує і хтось уже чекає → НЕ додаємось (третій запуск не має сенсу:
#     той, хто чекає, і так перерахує все свіже). Це «злипання» замість нескінченної
#     черги однакових завдань.
#
# Коди виходу: 0 — порахували; 75 — не стали в чергу, бо там уже хтось є (це НЕ помилка).
set -u
LOCKDIR="${RUNLOCK_DIR:-/var/lock}"
RUN_LOCK="$LOCKDIR/unitex-finrep-run.lock"
WAIT_LOCK="$LOCKDIR/unitex-finrep-wait.lock"
TARGET="${1:-/root/unitex-finrep/run.sh}"
MAXWAIT="${MAXWAIT:-1800}"          # скільки максимум чекати своєї черги, секунд

mkdir -p "$LOCKDIR" 2>/dev/null || true
exec 8>"$WAIT_LOCK"
exec 9>"$RUN_LOCK"

# Місце в черзі — рівно одне. Не вдалось зайняти → там уже хтось чекає.
if ! flock -n 8; then
  echo "QUEUE_SKIP: перерахунок уже виконується, і ще один уже чекає в черзі — цей запуск не потрібен"
  exit 75
fi

# Чекаємо, поки звільниться сам перерахунок.
if ! flock -w "$MAXWAIT" 9; then
  echo "QUEUE_TIMEOUT: не дочекались своєї черги за ${MAXWAIT}с"
  exit 75
fi

# Місце в черзі звільняємо ОДРАЗУ, як почали рахувати:
# поки ми рахуємо, наступний охочий має право стати в чергу.
flock -u 8

echo "QUEUE_RUN: почав перерахунок $TARGET"
/bin/bash "$TARGET"
rc=$?
echo "QUEUE_DONE: перерахунок завершено, код $rc"
exit $rc
