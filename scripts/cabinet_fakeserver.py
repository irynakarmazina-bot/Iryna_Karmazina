class FakeResp:
    headers = {"Content-Type": "application/pdf"}

    def __init__(self, url):
        self.url = url

    def read(self):
        return b"%PDF-1.4 fake " + self.url.encode()

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


